// Conversion d'un puzzle ASCII en données de jeu
function parsePuzzle(p) {
    const rows = p.grid.length, cols = Math.max(...p.grid.map(l => l.length));
    const mines = new Uint8Array(rows * cols);
    const starts = [];
    p.grid.forEach((line, r) => {
        for (let c = 0; c < cols; c++) {
            const ch = line[c] || '.';
            if (ch === '*') mines[r * cols + c] = 1;
            else if (ch === 'S') starts.push(r * cols + c);
        }
    });
    return { rows, cols, mines, starts, mineCount: mines.reduce((a, b) => a + b, 0) };
}

